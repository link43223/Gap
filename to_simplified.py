for fname in ['articles.js', 'gap-share.html']:
    with open(fname, 'r', encoding='utf-8') as f:
        content = f.read()
    def fix(m):
        cn = m.group(1)
        for t, s in sorted(t2s.items(), key=lambda x: -len(x[0])):
            cn = cn.replace(t, s)
        return 'titleCn:"' + cn + '"'
    content = re.sub(r'titleCn:"([^"]*)"', fix, content)
    with open(fname, 'w', encoding='utf-8') as f:
        f.write(content)
    print(fname + ': done')
